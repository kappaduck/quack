namespace KappaDuck.Quack.UI.Dialogs;

/// <summary>
/// The order in which message box buttons are laid out.
/// </summary>
public enum MessageBoxButtonOrder
{
    /// <summary>
    /// Buttons are placed from left to right, in the order they were provided.
    /// </summary>
    LeftToRight = 0,

    /// <summary>
    /// Buttons are placed from right to left, in the order they were provided.
    /// </summary>
    RightToLeft = 1
}
