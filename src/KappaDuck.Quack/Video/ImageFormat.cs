namespace KappaDuck.Quack.Video;

/// <summary>
/// Represents an image format.
/// </summary>
public enum ImageFormat
{
    /// <summary>
    /// The AVIF format.
    /// </summary>
    AVIF = 0,

    /// <summary>
    /// The BMP (Bitmap) format.
    /// </summary>
    BMP = 1,

    /// <summary>
    /// The CUR (Cursor) format.
    /// </summary>
    CUR = 2,

    /// <summary>
    /// The GIF format.
    /// </summary>
    GIF = 3,

    /// <summary>
    /// The ICO (Windows Icon) format.
    /// </summary>
    ICO = 4,

    /// <summary>
    /// The JPG format.
    /// </summary>
    JPG = 5,

    /// <summary>
    /// The PNG format.
    /// </summary>
    PNG = 6,

    /// <summary>
    /// The TGA format.
    /// </summary>
    TGA = 7,

    /// <summary>
    /// The WEBP format.
    /// </summary>
    WEBP = 8
}
